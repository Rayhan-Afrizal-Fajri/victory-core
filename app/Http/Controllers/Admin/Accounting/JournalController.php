<?php

namespace App\Http\Controllers\Admin\Accounting;

use App\Http\Controllers\Controller;
use App\Models\Accounting\ChartOfAccount;
use App\Models\Accounting\JournalEntry;
use App\Services\Accounting\AccountingJournalService;
use Illuminate\Http\Request;
use Inertia\Inertia;
use Inertia\Response;

class JournalController extends Controller
{
    protected AccountingJournalService $journalService;

    public function __construct(AccountingJournalService $journalService)
    {
        $this->journalService = $journalService;
    }

    public function index(Request $request): Response
    {
        $query = JournalEntry::with(['lines.account', 'jobTicket', 'creator']);

        if ($request->filled('reference_type')) {
            $query->where('reference_type', $request->reference_type);
        }

        if ($request->filled('start_date')) {
            $query->where('entry_date', '>=', $request->start_date);
        }

        if ($request->filled('end_date')) {
            $query->where('entry_date', '<=', $request->end_date);
        }

        $journals = $query->orderByDesc('entry_date')
            ->orderByDesc('id')
            ->paginate(25)
            ->withQueryString()
            ->through(function ($entry) {
                return [
                    'id' => $entry->id,
                    'entryNumber' => $entry->entry_number,
                    'date' => $entry->entry_date ? $entry->entry_date->format('Y-m-d') : '',
                    'description' => $entry->description,
                    'referenceType' => $entry->reference_type,
                    'referenceId' => $entry->reference_id,
                    'jobTicketNo' => $entry->jobTicket ? $entry->jobTicket->no_job_ticket : null,
                    'totalDebit' => (float) $entry->total_debit,
                    'totalCredit' => (float) $entry->total_credit,
                    'isAutoGenerated' => (bool) $entry->is_auto_generated,
                    'status' => $entry->status,
                    'creator' => $entry->creator ? $entry->creator->name : 'Sistem',
                    'lines' => $entry->lines->map(function ($line) {
                        return [
                            'id' => $line->id,
                            'accountId' => $line->account_id,
                            'accountCode' => $line->account ? $line->account->account_code : '',
                            'accountName' => $line->account ? $line->account->account_name : '',
                            'debit' => (float) $line->debit,
                            'credit' => (float) $line->credit,
                            'memo' => $line->memo,
                        ];
                    }),
                ];
            });

        $accounts = ChartOfAccount::where('is_active', true)
            ->orderBy('account_code')
            ->get(['id', 'account_code', 'account_name', 'normal_balance']);

        return Inertia::render('admin/accounting/journals', [
            'journals' => $journals,
            'accounts' => $accounts,
            'filters' => $request->only(['reference_type', 'start_date', 'end_date']),
        ]);
    }

    public function store(Request $request)
    {
        $validated = $request->validate([
            'entry_date' => 'required|date',
            'description' => 'required|string',
            'lines' => 'required|array|min:2',
            'lines.*.account_id' => 'required|exists:chart_of_accounts,id',
            'lines.*.debit' => 'required|numeric|min:0',
            'lines.*.credit' => 'required|numeric|min:0',
            'lines.*.memo' => 'nullable|string',
        ]);

        try {
            $this->journalService->createEntry(
                [
                    'entry_date' => $validated['entry_date'],
                    'description' => $validated['description'],
                    'reference_type' => 'manual',
                    'is_auto_generated' => false,
                    'status' => 'posted',
                    'created_by' => auth()->id(),
                ],
                $validated['lines']
            );

            return back()->with('success', 'Jurnal manual berhasil disimpan dan diposting!');
        } catch (\Exception $e) {
            return back()->with('error', $e->getMessage());
        }
    }
}
